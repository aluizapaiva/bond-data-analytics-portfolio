# ── 6.2  Recommendation assignment function ──────────────────────────────────

def assign_recommendation(cost_metric, benchmark):
    """
    Assign recommendation based on cost metric vs benchmark ratio.

    Uses the sigmoid-inspired threshold framework agreed on March 13:
      Scale Up  : cost < 70% of benchmark   -> strong efficiency
      Maintain  : 70-110% of benchmark       -> on-target
      Optimise  : 110-160% of benchmark      -> above benchmark but recoverable
      Pause     : cost > 160% of benchmark   -> poor return
    """
    if pd.isna(cost_metric) or pd.isna(benchmark) or benchmark == 0:
        return np.nan
    ratio = cost_metric / benchmark
    if ratio < 0.70:
        return 'Scale Up'
    elif ratio < 1.10:
        return 'Maintain'
    elif ratio < 1.60:
        return 'Optimise'
    else:
        return 'Pause'


def assign_binary_label(cost_metric, benchmark):
    """Binary simplification: Scale vs Do Not Scale."""
    if pd.isna(cost_metric) or pd.isna(benchmark) or benchmark == 0:
        return np.nan
    return 'Scale' if cost_metric / benchmark < 1.10 else 'Do Not Scale'

