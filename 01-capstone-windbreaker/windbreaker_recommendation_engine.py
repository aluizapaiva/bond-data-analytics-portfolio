# ── 7.1  Optimise sub-signals ────────────────────────────────────────────────

def add_optimise_signals(df, goal='leads'):
    """
    Add sub-signals to support the Optimise recommendation.

    Signals aligned with the agency partner's agreed optimisation levers:
      1. Spend pacing    — daily spend relative to peers (budget allocation)
      2. CPM efficiency  — cost-per-impression as proxy for placement quality
      3. Frequency fatigue — high frequency suggests creative refresh needed
    """
    df = df.copy()

    # Signal 1: Spend pacing
    if 'date_end' in df.columns and df['date_end'].notna().any():
        df['days_active'] = (df['date_end'] - df['date_start']).dt.days + 1
    else:
        df['days_active'] = np.nan
    df['daily_spend'] = df['spend'] / df['days_active'].replace(0, np.nan)

    q25_daily = df['daily_spend'].quantile(0.25)
    df['flag_low_daily_spend'] = (df['daily_spend'] < q25_daily).astype(int)

    # Signal 2: CPM efficiency (placement quality proxy)
    if 'cpm' in df.columns:
        median_cpm = df['cpm'].median()
        df['flag_high_cpm'] = (df['cpm'] > median_cpm * 1.3).astype(int)
    else:
        df['flag_high_cpm'] = 0

    # Signal 3: Frequency fatigue
    if 'frequency' in df.columns:
        df['flag_high_frequency'] = (df['frequency'] > 3.0).astype(int)
    else:
        df['flag_high_frequency'] = 0

    # Summary signal for Optimise rows
    df['optimise_focus'] = np.where(
        df['recommendation'] == 'Optimise',
        df[['flag_low_daily_spend', 'flag_high_cpm', 'flag_high_frequency']].apply(
            lambda row: ', '.join(filter(None, [
                'Budget pacing/spend allocation' if row['flag_low_daily_spend'] else '',
                'Placement cost (high CPM)'      if row['flag_high_cpm'] else '',
                'Creative refresh (frequency)'   if row['flag_high_frequency'] else '',
            ])) or 'Review overall efficiency',
            axis=1
        ),
        ''
    )

    return df

