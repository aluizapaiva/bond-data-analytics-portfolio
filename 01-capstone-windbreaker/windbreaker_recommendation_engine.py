def clean_client(df, name):
    """
    Clean a single client DataFrame. Handles both daily and monthly files.
    """
    granularity = df['_granularity'].iloc[0] if '_granularity' in df.columns else 'unknown'

    # Drop fully empty columns
    df = df.dropna(axis=1, how='all').copy()

    # Rename columns using the mapping
    df = df.rename(columns={k: v for k, v in COL_MAP.items() if k in df.columns})

    # Drop unnamed index columns (CLIENT_B artefact)
    df = df.loc[:, ~df.columns.str.startswith('Unnamed')]

    # ── Fallback column detection ──────────────────────────────────────────
    if 'spend' not in df.columns:
        spend_candidates = [c for c in df.columns if 'spent' in str(c).lower() or 'spend' in str(c).lower()]
        if spend_candidates:
            df = df.rename(columns={spend_candidates[0]: 'spend'})
            print(f"  [{name}] Fallback: mapped '{spend_candidates[0]}' -> 'spend'")

    if 'impressions' not in df.columns:
        imp_candidates = [c for c in df.columns if 'impression' in str(c).lower()]
        if imp_candidates:
            df = df.rename(columns={imp_candidates[0]: 'impressions'})

    if 'cpm' not in df.columns:
        cpm_candidates = [c for c in df.columns if 'cpm' in str(c).lower()]
        if cpm_candidates:
            df = df.rename(columns={cpm_candidates[0]: 'cpm'})

    # Replace '-' with NaN in ranking-style columns
    for col in ['quality_ranking', 'engagement_rate_ranking', 'conversion_rate_ranking']:
        if col in df.columns:
            df[col] = df[col].replace('-', np.nan)

    # ── Date parsing (granularity-aware) ──────────────────────────────────
    # Priority 1: 'day' column (daily files)
    if 'day' in df.columns:
        df['date_start'] = pd.to_datetime(df['day'], errors='coerce')
        df['date_end']   = df['date_start']  # same day
        print(f"  [{name}] Parsed daily dates from 'Day' column")

    # Priority 2: 'date_start'/'date_end' already exist (Reporting starts/ends)
    elif 'date_start' in df.columns:
        df['date_start'] = pd.to_datetime(df['date_start'], errors='coerce')
        if 'date_end' in df.columns:
            df['date_end'] = pd.to_datetime(df['date_end'], errors='coerce')

    # Priority 3: 'month' column (monthly format: "2024-01-01 - 2024-01-31")
    if 'month' in df.columns:
        if 'date_start' not in df.columns or df['date_start'].isna().all():
            df['date_start'] = pd.to_datetime(
                df['month'].str.split(' - ').str[0], errors='coerce'
            )
            df['date_end'] = pd.to_datetime(
                df['month'].str.split(' - ').str[1], errors='coerce'
            )
            print(f"  [{name}] Parsed monthly dates from 'Month' column")

    # Cast numerics
    for col in NUMERIC_COLS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')

    # Derive year_month for grouping (works for both daily and monthly)
    if 'date_start' in df.columns:
        df['year_month'] = df['date_start'].dt.to_period('M')

    # Derive day_of_week for daily data
    if granularity == 'daily' and 'date_start' in df.columns:
        df['day_of_week'] = df['date_start'].dt.day_name()
        df['day_of_week_num'] = df['date_start'].dt.dayofweek  # 0=Mon, 6=Sun

    # Derive cost_per_purchase if not in export (CLIENT_C daily CSVs)
    if 'purchases' in df.columns and 'cost_per_purchase' not in df.columns:
        purchases = pd.to_numeric(df.get('purchases', 0), errors='coerce')
        if (purchases > 0).any():
            df['cost_per_purchase'] = df['spend'] / purchases.replace(0, np.nan)
            derived_count = df['cost_per_purchase'].notna().sum()
            print(f"  [{name}] Derived cost_per_purchase: {derived_count} rows")

    # Drop zero-spend rows (no campaign activity)
    if 'spend' in df.columns:
        before = len(df)
        df = df[df['spend'].notna() & (df['spend'] > 0)]
        dropped = before - len(df)
        if dropped > 0:
            print(f"  [{name}] Dropped {dropped} zero/null spend rows")
    else:
        print(f"  [{name}] WARNING: 'spend' column not found")
        print(f"           Available columns: {list(df.columns[:15])}")

    # Tag client and granularity
    df['_client'] = name
    df['_granularity'] = granularity
    return df


