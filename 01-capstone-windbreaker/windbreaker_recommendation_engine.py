# ── 8.1  Feature engineering pipeline ────────────────────────────────────────

# NOTE: CLIENT_A daily CSV exports do not include 'cpm' or 'ctr_link' columns.
# These are present in the monthly xlsx but absent from the daily Meta export.
# The daily feature matrix therefore has 9 features vs 12 for monthly.
# This is a data availability constraint, not a pipeline error.
# Impact: cpm and ctr_link cannot be used as predictors in the daily model.

def engineer_features(df, target_col, critical_cols=None):
    """
    Build the feature matrix X and label vector y for the XGBoost model.

    Parameters
    ----------
    df : pd.DataFrame
        Labelled dataset (must contain 'recommendation' column).
    target_col : str
        The goal-specific KPI column (e.g. 'cpl_calc', 'cost_per_purchase').
    critical_cols : list or None
        If provided (from KPI guide), only these columns are used as core
        features.

    Features:
    - Core spend/efficiency metrics (filtered by KPI guide if available)
    - Temporal features (month-of-year, quarter, day-of-week for daily)
    - Rolling averages (7-day for daily, 3-month for monthly)
    - Ratio features (spend efficiency ratios)
    """
    df = df.copy().sort_values('date_start')
    granularity = df['_granularity'].iloc[0] if '_granularity' in df.columns else 'monthly'

    # ── Core features (KPI-guide-aware) ────────────────────────────────────
    all_candidates = ['spend', 'impressions', 'reach', 'frequency', 'cpm',
                      'ctr_link', 'cpc_link', 'clicks_all', 'ctr_all']

    if critical_cols is not None and len(critical_cols) > 0:
        core_candidates = [c for c in all_candidates if c in critical_cols]
        if 'spend' not in core_candidates and 'spend' in df.columns:
            core_candidates.insert(0, 'spend')
        dropped = set(all_candidates) - set(core_candidates) - {'spend'}
        if dropped:
            print(f"  [KPI filter] Excluded non-critical features: {sorted(dropped)}")
    else:
        core_candidates = all_candidates

    feature_cols = [c for c in core_candidates if c in df.columns]

    # ── Temporal features ──────────────────────────────────────────────────
    if 'date_start' in df.columns:
        df['month_of_year'] = df['date_start'].dt.month
        df['quarter']       = df['date_start'].dt.quarter
        feature_cols += ['month_of_year', 'quarter']

    # Day-of-week feature (daily data only — useful for XGBoost)
    if granularity == 'daily' and 'day_of_week_num' in df.columns:
        feature_cols.append('day_of_week_num')
    elif granularity == 'daily' and 'date_start' in df.columns:
        df['day_of_week_num'] = df['date_start'].dt.dayofweek
        feature_cols.append('day_of_week_num')

    # ── Ratio features ─────────────────────────────────────────────────────
    df['ctr_x_spend']   = df.get('ctr_link', 0) * df['spend']
    df['spend_per_imp'] = df['spend'] / df['impressions'].replace(0, np.nan)
    df['reach_ratio']   = df['reach'] / df['impressions'].replace(0, np.nan)
    feature_cols += ['ctr_x_spend', 'spend_per_imp', 'reach_ratio']

    # ── Rolling averages (granularity-aware) ──────────────────────────────
    if 'date_start' in df.columns and len(df) >= 6:
        if granularity == 'daily':
            # 7-day rolling average per campaign (avoid mixing time series)
            group_col = 'adset_name' if 'adset_name' in df.columns else 'campaign_name'
            if group_col in df.columns:
                df = df.sort_values([group_col, 'date_start'])
                for col in [target_col, 'cpm', 'ctr_link']:
                    if col in df.columns:
                        new_col = f'{col}_7d_avg'
                        df[new_col] = df.groupby(group_col)[col].transform(
                            lambda x: x.rolling(7, min_periods=1).mean()
                        )
                        feature_cols.append(new_col)
            else:
                # Fallback: global rolling
                df = df.set_index('date_start').sort_index()
                for col in [target_col, 'cpm', 'ctr_link']:
                    if col in df.columns:
                        new_col = f'{col}_7d_avg'
                        df[new_col] = df[col].rolling(7, min_periods=1).mean()
                        feature_cols.append(new_col)
                df = df.reset_index()
        else:
            # Monthly: 3-month trailing average
            df = df.set_index('date_start').sort_index()
