#    The P(Scale) value IS the confidence score.
# ──────────────────────────────────────────────────────────────────

# Thresholds (adjustable — to be validated with the client analyst and the client lead)
SIGMOID_THRESHOLDS = {
    'scale_up': 0.70,   # P(Scale) above this -> Scale Up
    'maintain': 0.40,   # P(Scale) between maintain and scale_up -> Maintain
    'optimise': 0.20,   # P(Scale) between optimise and maintain -> Optimise
    # Below optimise threshold -> Pause
}

def sigmoid_to_4class(p_scale, thresholds=SIGMOID_THRESHOLDS):
    """
    Map binary sigmoid probability P(Scale) to 4 recommendation tiers.

    This is the advisor's core suggestion: train binary, use probabilities
    as a continuous signal, and bin into actionable categories.

    Parameters
    ----------
    p_scale : float
        Probability of 'Scale' from the binary classifier (0 to 1).
    thresholds : dict
        Threshold values for each tier boundary.

    Returns
    -------
    recommendation : str
        One of 'Scale Up', 'Maintain', 'Optimise', 'Pause'.
    """
    if pd.isna(p_scale) or pd.isna(thresholds) or pd.isna(thresholds['scale_up']):
        return np.nan
    if p_scale >= thresholds['scale_up']:
        return 'Scale Up'
    elif p_scale >= thresholds['maintain']:
        return 'Maintain'
    elif p_scale >= thresholds['optimise']:
        return 'Optimise'
    else:
        return 'Pause'

