# ── 12.1  Feature importance extraction ──────────────────────────────
def plot_feature_importance(model, feature_names, title, color, top_n=15):
    """Plot XGBoost feature importance (gain-based) as a horizontal bar chart."""
    importances = model.feature_importances_
    feat_imp = pd.DataFrame({
        'feature': feature_names,
        'importance': importances
    }).sort_values('importance', ascending=True).tail(top_n)

    fig, ax = plt.subplots(figsize=(10, max(4, top_n * 0.35)))
    ax.barh(feat_imp['feature'], feat_imp['importance'], color=color,
            edgecolor='white', alpha=0.85)
    ax.set_title(title, fontweight='bold', fontsize=13)
    ax.set_xlabel('Feature Importance (Gain)')

    for i, (val, name) in enumerate(zip(feat_imp['importance'], feat_imp['feature'])):
        ax.text(val + 0.002, i, f'{val:.3f}', va='center', fontsize=9)

    plt.tight_layout()
    plt.show()
    return feat_imp

