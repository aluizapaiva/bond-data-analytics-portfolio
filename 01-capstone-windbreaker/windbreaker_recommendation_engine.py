# ── Loader: monthly Excel ─────────────────────────────────────────────────
def load_monthly_excel(name, path, header_row=0, sheet='Raw Data Report'):
    """Load a client monthly Excel file with auto-header detection."""
    df = pd.read_excel(path, sheet_name=sheet, header=header_row)
    df = df.dropna(how='all')

    expected_cols = {'Amount spent (AUD)', 'Month', 'Impressions', 'Reach'}
    if len(set(df.columns) & expected_cols) == 0:
        for try_header in [0, 1, 2, 3]:
            if try_header == header_row:
                continue
            df_retry = pd.read_excel(path, sheet_name=sheet, header=try_header)
            df_retry = df_retry.dropna(how='all')
            if len(set(df_retry.columns) & expected_cols) > 0:
                df = df_retry
                print(f"  [{name}] Auto-detected header at row {try_header}")
                break

    df['_client'] = name
    df['_granularity'] = 'monthly'
    print(f"  {name}: {len(df)} rows x {len(df.columns)} cols  [MONTHLY xlsx]")
    return df

# ── Loader: daily CSVs (concatenate multiple files) ────────────────────────
def load_daily_csvs(name, file_list):
    """Load and concatenate multiple daily CSV files for a client."""
    frames = []
    for csv_path in file_list:
        try:
            df = pd.read_csv(csv_path)
            df = df.dropna(how='all')
            fname = Path(csv_path).name
            print(f"    {fname}: {len(df)} rows")
            frames.append(df)
        except FileNotFoundError:
            print(f"    NOT FOUND: {Path(csv_path).name}")
        except Exception as e:
            print(f"    ERROR: {Path(csv_path).name} — {e}")

    if frames:
        combined = pd.concat(frames, ignore_index=True)
        combined['_client'] = name
        combined['_granularity'] = 'daily'
        print(f"  {name}: {len(combined)} rows total  [DAILY CSV, {len(frames)} files]")
        return combined
    else:
        print(f"  {name}: No daily CSV data loaded")
        return pd.DataFrame()

